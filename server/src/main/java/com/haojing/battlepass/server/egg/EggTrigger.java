package com.haojing.battlepass.server.egg;

/**
 * 用途：彩蛋判定的触发时机。
 *
 * <p>为什么需要区分时机：13 个彩蛋里，有的是"某个事件发生的瞬间"判定
 * （钓鱼成功、进入新群系、树苗长成），有的只能在周期性采样里判定
 * （连续停留、静止、累计放置数达标那一刻的"周边无敌对生物"），
 * 还有的只在**长夜窗口结束**这一瞬间才有意义（守夜人、晨归）。
 * 把时机作为显式参数传进判定器，就能避免"用一个每 20 tick 的轮询去硬凑所有条件"
 * 这种必然写错的做法（例如钓鱼成功根本没有轮询信号）。
 */
public enum EggTrigger {

    /** 周期性采样（默认每 20 tick 一次；静听因 §6 明确要求"每 tick 位移"而按 tick 采样）。 */
    POLL,

    /** 玩家放置了一个方块。 */
    PLACE_BLOCK,

    /** 玩家钓鱼成功。 */
    FISH,

    /** 玩家进入/停留在某群系（每次采样会上报当前群系）。 */
    BIOME_ENTER,

    /** 已记录的树苗长成了树。 */
    SAPLING_GROWN,

    /** 长夜窗口结束（06:00 那一刻仍在线的玩家）。 */
    NIGHT_WINDOW_END
}
